import { mkdir, writeFile } from "node:fs/promises";
import sharp from "sharp";
import { freshProfile } from "../src/abc/fields.ts";
import { renderBiodataJpeg } from "../src/abc/biodata.ts";

const p=freshProfile();
p.candidate.full_name="Faizan Ali";
p.candidate.age_years=27;
p.candidate.height_cm=178;
p.candidate.current_location.city="Delhi";
p.candidate.marital_status="Never married";
p.candidate.ancestral_location.city_or_town="Aligarh";
p.candidate.education.highest_qualification="Bachelor of Technology";
p.candidate.occupation.profession_or_role="Engineer";
p.family.father.name="Ahmed Ali";
p.family.father.profession="Teacher";
p.family.father.education="Master of Arts";
p.family.mother.name="Fatima Ali";
p.family.mother.profession="Homemaker";
p.family.mother.education="Bachelor of Arts";
p.family.siblings.brothers_count=1;
p.family.siblings.sisters_count=2;
p.candidate.personal_introduction="Enjoys reading, learning and spending time with family.";
p.partner_preferences.preferred_age_range="23 to 28";
const picture=await sharp({create:{width:300,height:340,channels:3,background:{r:192,g:224,b:210}}}).png().toBuffer();
const jpeg=await renderBiodataJpeg(p,"data:image/png;base64,"+picture.toString("base64"));
const metadata=await sharp(jpeg).metadata();
if(metadata.width!==1080||metadata.height!==1350)throw Error("Incorrect WhatsApp image dimensions");
await mkdir("abc-biodata-preview",{recursive:true});
await writeFile("abc-biodata-preview/ABC-Biodata-v1.3-Sample.jpg",jpeg);
